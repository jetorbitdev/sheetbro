#!/usr/bin/env python3
"""Generates src/functionList.ts: every function IronCalc implements, grouped
by category. Re-run after bumping the ironcalc dependency:

    python3 scripts/gen_functions.py

Categories come from the section comments in IronCalc's `impl_function_lookup!`
table; the Excel names come from its English language data, read through a
throwaway Rust example.
"""
import glob, json, os, re, subprocess, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
tauri = os.path.join(root, "src-tauri")
srcs = sorted(glob.glob(os.path.expanduser(
    "~/.cargo/registry/src/*/ironcalc_base-*/src/functions/mod.rs")))
if not srcs:
    sys.exit("ironcalc_base source not found; run `cargo fetch` first")
text = open(srcs[-1]).read()

# field -> category, from the lookup table's section comments
table = text[text.index("impl_function_lookup! {"):]
CATEGORY = [
    ("Logical", "Logical"), ("Mathematical", "Math"), ("Information", "Info"),
    ("Lookup", "Lookup"), ("Dynamic array", "Array"), ("Text", "Text"),
    ("Statistical", "Statistical"), ("Compatibility", "Statistical"),
    ("Date", "Date"), ("Financial", "Financial"), ("Engineering", "Engineering"),
    ("Database", "Database"),
]
cat = None
field_cat = {}
for line in table.splitlines()[1:]:
    line = line.strip()
    if line.startswith("//"):
        label = line[2:].strip()
        cat = next((c for k, c in CATEGORY if label.startswith(k)), cat)
    elif "=>" in line and cat:
        field_cat[line.split("=>")[0].strip()] = cat
    elif line.startswith("}"):
        break

# field -> English name, via a generated example program
fields = list(field_cat)
example_dir = os.path.join(tauri, "examples")
os.makedirs(example_dir, exist_ok=True)
example = os.path.join(example_dir, "dump_functions.rs")
with open(example, "w") as f:
    f.write("fn main() {\n    let l = ironcalc::base::language::get_language(\"en\").unwrap();\n")
    for fld in fields:
        f.write(f'    println!("{fld.replace("r#", "")}\\t{{}}", l.functions.{fld});\n')
    f.write("}\n")
try:
    out = subprocess.run(["cargo", "run", "-q", "--example", "dump_functions"],
                         cwd=tauri, check=True, capture_output=True, text=True).stdout
finally:
    os.remove(example)
    try:
        os.rmdir(example_dir)
    except OSError:
        pass

groups = {}
for line in out.splitlines():
    fld, name = line.split("\t")
    c = field_cat.get(fld) or field_cat.get("r#" + fld)
    groups.setdefault(c, []).append(name)
result = {c: sorted(set(v)) for c, v in sorted(groups.items())}
dest = os.path.join(root, "src", "functionList.ts")
with open(dest, "w") as f:
    f.write("// Generated by scripts/gen_functions.py - do not edit.\n")
    f.write("export const FUNCTION_LIST: Record<string, string[]> = ")
    f.write(json.dumps(result, indent=2))
    f.write(";\n")
print(sum(map(len, result.values())), "functions:", {c: len(v) for c, v in result.items()})
